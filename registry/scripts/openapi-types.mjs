// Writes tests/generated/openapi.ts: one TypeScript type per schema in openapi.json
// (components.schemas), for the type-level contract check in tests/contract.ts.
// It covers the JSON Schema that Pydantic and FastAPI emit: objects, arrays, $ref,
// anyOf, enum, const, null and the scalar types. Anything else becomes `unknown`.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

const root = join(dirname(fileURLToPath(import.meta.url)), "..")
const document = JSON.parse(readFileSync(join(root, "openapi.json"), "utf8"))
const schemas = document.components?.schemas ?? {}

const scalars = { string: "string", integer: "number", number: "number", boolean: "boolean", null: "null" }

function type(schema) {
  if (!schema || typeof schema !== "object") return "unknown"
  if (schema.$ref) return `components["schemas"][${JSON.stringify(schema.$ref.split("/").pop())}]`
  if (schema.const !== undefined) return JSON.stringify(schema.const)
  if (schema.enum) return schema.enum.map((value) => JSON.stringify(value)).join(" | ")
  const union = schema.anyOf ?? schema.oneOf
  if (union) return union.map((part) => `(${type(part)})`).join(" | ")
  if (Array.isArray(schema.type)) return schema.type.map((t) => type({ ...schema, type: t })).join(" | ")
  if (schema.type === "array") return `(${type(schema.items)})[]`
  if (schema.type === "object" || schema.properties) {
    const required = new Set(schema.required ?? [])
    const fields = Object.entries(schema.properties ?? {}).map(
      ([name, field]) => `${JSON.stringify(name)}${required.has(name) ? "" : "?"}: ${type(field)}`,
    )
    const extra = schema.additionalProperties
    if (extra === true || (extra && typeof extra === "object")) {
      fields.push(`[key: string]: ${extra === true ? "unknown" : type(extra)}`)
    } else if (extra === undefined && !schema.properties) {
      fields.push("[key: string]: unknown")
    }
    return `{ ${fields.join("; ")} }`
  }
  return scalars[schema.type] ?? "unknown"
}

const lines = [
  "// Generated by scripts/openapi-types.mjs from openapi.json. Do not edit.",
  "export type components = {",
  "  schemas: {",
  ...Object.keys(schemas)
    .sort()
    .map((name) => `    ${JSON.stringify(name)}: ${type(schemas[name])}`),
  "  }",
  "}",
  "",
]
const output = join(root, "tests", "generated", "openapi.ts")
mkdirSync(dirname(output), { recursive: true })
writeFileSync(output, lines.join("\n"))
console.log(`wrote ${Object.keys(schemas).length} schema types to tests/generated/openapi.ts`)
